def _clean_old_temp_logs() -> None:
    """Clean up temporary log files generated by the launcher in /tmp."""
    try:
        temp_dir = Path(tempfile.gettempdir())
        current_time = time.time()
        max_age_seconds = 24 * 3600
        for log_file in temp_dir.glob("launcher_error_*.log"):
            try:
                if (
                    log_file.is_file()
                    and current_time - log_file.stat().st_mtime
                    > max_age_seconds
                ):
                    log_file.unlink()
            except OSError:
                pass
    except Exception:
        pass


class ProcessRunner(QObject):
    """Run one supervised command and dispatch desktop notifications.

    Detached commands are launched independently and are not supervised.
    """

    outputReceived = Signal(str)
    processFinished = Signal(int, str)
    runningChanged = Signal()
    notificationError = Signal(str)

    def __init__(self, parent: QObject = None) -> None:
        """Create a runner owned by the optional Qt parent."""
        super().__init__(parent)
        self._process = QProcess(self)
        self._last_name = ""
        self._last_base_command = ""
        self._last_extra_args = ""
        self._output_buffer = ""
        self._last_log_path = ""
        self._notify_on_finish = False
        self._notification_processes: set[QProcess] = set()

        app = QCoreApplication.instance()
        if app is not None:
            app.aboutToQuit.connect(self._stop_notifications)

        self._process.readyReadStandardOutput.connect(self._handle_stdout)
        self._process.readyReadStandardError.connect(self._handle_stderr)
        self._process.finished.connect(self._handle_finished)
        self._process.errorOccurred.connect(self._handle_error)
        self._process.stateChanged.connect(
            lambda state: self.runningChanged.emit()
        )

    @Property(bool, notify=runningChanged)
    def running(self) -> bool:
        """Return whether the supervised process is starting or running."""
        return self._process.state() != QProcess.NotRunning

    @Slot(str, str, str, bool)
    @Slot(str, str, str, bool, bool)
    def start_command_with_args(
        self,
        name: str,
        base_command: str,
        extra_args: str,
        detached: bool = False,
        notify: bool = False,
    ) -> None:
        """Run a command through Bash after expanding paths and variables.

        ``detached`` launches without supervision; ``notify`` requests a
        completion notification for supervised commands. Starting another
        supervised command stops the current one.
        """
        raw_command = f"{base_command} {extra_args}".strip()
        if not raw_command:
            return

        expanded_command = os.path.expanduser(os.path.expandvars(raw_command))

        if detached:
            QProcess.startDetached("/bin/bash", ["-c", expanded_command])
            self.outputReceived.emit(f"$ {expanded_command} (Detached)\n")
            self.processFinished.emit(
                0, "\n[Process launched in detached mode]\n"
            )
            return

        if self._process.state() != QProcess.NotRunning:
            self._process.kill()
            if not self._process.waitForFinished(3000):
                self.notificationError.emit(
                    "Could not stop the previous command."
                )
                return

        self._last_name = name
        self._last_base_command = base_command
        self._last_extra_args = extra_args
        self._output_buffer = ""
        self._last_log_path = ""
        self._notify_on_finish = notify

        self._process.setStandardInputFile(os.devnull)
        self.outputReceived.emit(f"$ {expanded_command}\n")
        self._process.start("/bin/bash", ["-c", expanded_command])

    @Slot()
    def terminate_process(self) -> None:
        """Terminate the running subprocess."""
        if self._process.state() != QProcess.NotRunning:
            self._process.kill()
            self.outputReceived.emit("\n[Process cancelled by user]\n")

    @Slot(str, str, result=bool)
    def save_text_to_file(self, file_url: str, text: str) -> bool:
        """Save provided console text output to a local text file."""
        try:
            local_path = QUrl(file_url).toLocalFile() or file_url
            Path(local_path).write_text(text, encoding="utf-8")
            return True
        except (OSError, ValueError):
            return False

    def _handle_error(self, error: QProcess.ProcessError) -> None:
        """Report QProcess startup or runtime failures immediately."""
        error_messages = {
            QProcess.FailedToStart: (
                "Failed to start (check file path, shebang, or +x "
                "permissions)."
            ),
            QProcess.Crashed: "Process crashed unexpectedly.",
            QProcess.Timedout: "Process timed out.",
            QProcess.WriteError: "Write error to process.",
            QProcess.ReadError: "Read error from process.",
            QProcess.UnknownError: "Unknown process execution error.",
        }
        msg = error_messages.get(error, "Process error.")
        self.outputReceived.emit(f"\n[Error: {msg}]\n")
        if error == QProcess.FailedToStart:
            self.processFinished.emit(-1, f"\n[Execution aborted: {msg}]\n")
            if self._notify_on_finish:
                self._send_notification(-1)

    def _handle_stdout(self) -> None:
        """Handle standard output reading from the active process."""
        data = (
            self._process.readAllStandardOutput()
            .data()
            .decode("utf-8", errors="replace")
        )
        self._output_buffer += data
        self.outputReceived.emit(data)

    def _handle_stderr(self) -> None:
        """Handle standard error reading from the active process."""
        data = (
            self._process.readAllStandardError()
            .data()
            .decode("utf-8", errors="replace")
        )
        self._output_buffer += data
        self.outputReceived.emit(data)

    def _handle_finished(
        self, exit_code: int, exit_status: QProcess.ExitStatus
    ) -> None:
        """Handle process termination and dispatch desktop notifications."""
        status_msg = f"\n[Process finished with exit code {exit_code}]\n"
        self.outputReceived.emit(status_msg)
        self.processFinished.emit(exit_code, status_msg)

        if exit_code != 0 and self._output_buffer.strip():
            try:
                fd, path = tempfile.mkstemp(
                    prefix="launcher_error_", suffix=".log"
                )
                with os.fdopen(fd, "w", encoding="utf-8") as f:
                    f.write(self._output_buffer)
                self._last_log_path = path
            except OSError as error:
                self._last_log_path = ""
                self.notificationError.emit(
                    f"Could not save command log: {error}"
                )

        if self._notify_on_finish:
            self._send_notification(exit_code)

    def _send_notification(self, exit_code: int) -> None:
        """Send a completion notification with actions for this execution.

        Keep the notification process alive until its action or closure, and
        retain this execution's command and log for the action callbacks.
        """
        name = self._last_name
        base_command = self._last_base_command
        extra_args = self._last_extra_args
        log_path = self._last_log_path
        title = (
            f"Command completed: {name}"
            if exit_code == 0
            else f"Command failed: {name}"
        )
        args = [
            "--app-name=Kumi",
            f"--icon={'dialog-ok' if exit_code == 0 else 'dialog-error'}",
            "--action=retry=Retry",
        ]
        if exit_code != 0 and log_path:
            args.append("--action=view=View Log")
        args.extend(
            ["--", title, f"Script finished with exit code {exit_code}."]
        )

        notification = QProcess(self)
        self._notification_processes.add(notification)

        def failed(error: QProcess.ProcessError) -> None:
            """Report a failure to start the notification process."""
            if error == QProcess.FailedToStart:
                self.notificationError.emit(
                    "Could not start notify-send: "
                    f"{notification.errorString()}"
                )
                self._notification_processes.discard(notification)
                notification.deleteLater()

        def finished(code: int, status: QProcess.ExitStatus) -> None:
            """Report notification errors or handle the selected action."""
            action = (
                bytes(notification.readAllStandardOutput())
                .decode("utf-8", errors="replace")
                .strip()
            )
            error = (
                bytes(notification.readAllStandardError())
                .decode("utf-8", errors="replace")
                .strip()
            )
            self._notification_processes.discard(notification)
            notification.deleteLater()
            if code != 0 or status != QProcess.NormalExit:
                detail = error or notification.errorString()
                self.notificationError.emit(
                    f"Could not send desktop notification: {detail}"
                )
            elif action == "retry":
                if self.running:
                    self.notificationError.emit(
                        "Cannot retry while another command is running."
                    )
                else:
                    self.start_command_with_args(
                        name, base_command, extra_args, False, True
                    )
            elif action == "view" and log_path:
                started, _ = QProcess.startDetached("xdg-open", [log_path])
                if not started:
                    self.notificationError.emit(
                        "Could not open the command log."
                    )

        notification.errorOccurred.connect(failed)
        notification.finished.connect(finished)
        notification.start("notify-send", args)

    def _stop_notifications(self) -> None:
        """Stop notification processes when the application exits."""
        for notification in self._notification_processes:
            notification.blockSignals(True)
            notification.kill()
            notification.waitForFinished(1000)
        self._notification_processes.clear()


class LauncherBackend(QObject):
    """Expose configuration, history, statistics and settings to QML."""

    favoritesChanged = Signal()
    sectionsChanged = Signal()
    statsChanged = Signal()
    modifierChanged = Signal()
    showCommandChanged = Signal()
    promptArgumentsChanged = Signal()
    showOutputWindowChanged = Signal()
    statusNotification = Signal(str, bool)

    def __init__(self, config_path: Path, parent: QObject = None) -> None:
        """Load configuration and related data beside ``config_path``."""
        super().__init__(parent)
        self._config_path = config_path
        self._sections: List[Dict[str, Any]] = []
        self._favorites: List[Dict[str, Any]] = []
        self._stats: Dict[str, Dict[str, Any]] = {}
        self._shortcut_modifier = "Ctrl+Shift"
        self._show_command = False
        self._prompt_arguments = False
        self._show_output_window = True

        self._base_dir = config_path.parent
        self._history_file = self._base_dir / "kumi_history.json"
        self._stats_file = self._base_dir / "kumi_stats.json"

        self._load_config()
        self._load_history()
        self._load_stats()

    def _load_config(self) -> None:
        """Load menu configuration and global settings from JSON."""
        if not self._config_path.exists():
            return
        try:
            with self._config_path.open("r", encoding="utf-8") as file:
                data = json.load(file)
                self._sections = data.get("sections", [])
                self._shortcut_modifier = data.get(
                    "shortcut_modifier", "Ctrl+Shift"
                )
                self._show_command = bool(data.get("show_command", False))
                self._prompt_arguments = bool(
                    data.get("prompt_arguments", False)
                )
                self._show_output_window = bool(
                    data.get("show_output_window", True)
                )
        except (json.JSONDecodeError, OSError):
            pass

    def _save_config_file(self) -> bool:
        """Save sections and global preferences to menu configuration JSON."""
        try:
            payload = {
                "shortcut_modifier": self._shortcut_modifier,
                "show_command": self._show_command,
                "prompt_arguments": self._prompt_arguments,
                "show_output_window": self._show_output_window,
                "sections": self._sections,
            }
            with self._config_path.open("w", encoding="utf-8") as file:
                json.dump(payload, file, indent=4, ensure_ascii=False)
            return True
        except OSError:
            return False

    def _load_history(self) -> None:
        """Load command execution history from JSON."""
        if self._history_file.exists():
            try:
                with self._history_file.open("r", encoding="utf-8") as file:
                    self._favorites = json.load(file)
            except (json.JSONDecodeError, OSError):
                self._favorites = []

    def _save_history(self) -> bool:
        """Atomically save history and report errors to the interface."""
        temp_path = None
        try:
            fd, name = tempfile.mkstemp(
                prefix=".kumi_history_",
                suffix=".tmp",
                dir=self._history_file.parent,
            )
            temp_path = Path(name)
            with os.fdopen(fd, "w", encoding="utf-8") as file:
                json.dump(self._favorites, file, indent=4)
            os.replace(temp_path, self._history_file)
            return True
        except OSError as exc:
            message = f"Could not save recent items: {exc}"
            if temp_path is not None:
                try:
                    temp_path.unlink(missing_ok=True)
                except OSError as cleanup_error:
                    message += (
                        f" (could not remove temporary file: {cleanup_error})"
                    )
            self.statusNotification.emit(message, False)
            return False

    def _load_stats(self) -> None:
        """Load execution frequency statistics from JSON."""
        if self._stats_file.exists():
            try:
                with self._stats_file.open("r", encoding="utf-8") as file:
                    self._stats = json.load(file)
            except (json.JSONDecodeError, OSError):
                self._stats = {}

    def _save_stats(self) -> None:
        """Save execution frequency statistics to JSON."""
        try:
            with self._stats_file.open("w", encoding="utf-8") as file:
                json.dump(self._stats, file, indent=4)
        except OSError:
            pass

    @Property("QString", notify=modifierChanged)
    def shortcutModifier(self) -> str:
        """Return current configured global shortcut modifier."""
        return self._shortcut_modifier

    @shortcutModifier.setter
    def shortcutModifier(self, modifier: str) -> None:
        """Set and save global shortcut modifier preference."""
        if self._shortcut_modifier != modifier:
            self._shortcut_modifier = modifier
            self._save_config_file()
            self.modifierChanged.emit()
            self.statusNotification.emit(
                f"Shortcut modifier updated to: {modifier}", True
            )

    @Property(bool, notify=showCommandChanged)
    def showCommand(self) -> bool:
        """Return whether command strings are displayed on launcher cards."""
        return self._show_command

    @showCommand.setter
    def showCommand(self, value: bool) -> None:
        """Set and save whether command strings are displayed on cards."""
        bool_val = bool(value)
        if self._show_command != bool_val:
            self._show_command = bool_val
            self._save_config_file()
            self.showCommandChanged.emit()
            state_label = "shown" if bool_val else "hidden"
            self.statusNotification.emit(
                f"Command preview {state_label}.", True
            )

    @Property(bool, notify=promptArgumentsChanged)
    def promptArguments(self) -> bool:
        """Return whether parameter prompt dialog opens globally on run."""
        return self._prompt_arguments

    @promptArguments.setter
    def promptArguments(self, value: bool) -> None:
        """Set and save global parameter prompt dialog preference."""
        bool_val = bool(value)
        if self._prompt_arguments != bool_val:
            self._prompt_arguments = bool_val
            self._save_config_file()
            self.promptArgumentsChanged.emit()
            state_label = "enabled" if bool_val else "disabled"
            self.statusNotification.emit(
                f"Global argument prompt {state_label}.", True
            )

    @Property(bool, notify=showOutputWindowChanged)
    def showOutputWindow(self) -> bool:
        """Return whether execution output window should be displayed."""
        return self._show_output_window

    @showOutputWindow.setter
    def showOutputWindow(self, value: bool) -> None:
        """Set and save execution output window preference."""
        bool_val = bool(value)
        if self._show_output_window != bool_val:
            self._show_output_window = bool_val
            self._save_config_file()
            self.showOutputWindowChanged.emit()
            state_label = "enabled" if bool_val else "disabled"
            self.statusNotification.emit(
                f"Execution output window {state_label}.", True
            )

    @Property("QVariantList", notify=sectionsChanged)
    def sections(self) -> List[Dict[str, Any]]:
        """Return configured menu sections."""
        return self._sections

    @Property("QVariantList", notify=favoritesChanged)
    def favorites(self) -> List[Dict[str, Any]]:
        """Return recently executed commands list."""
        return self._favorites

    @Slot(result="QVariantList")
    def get_shortcut_assignments(self) -> List[Dict[str, Any]]:
        """Scan menu sections for actions having shortcut assignments (1-9)."""
        shortcuts = [{"shortcutId": i, "item": None} for i in range(1, 10)]

        def _scan_items(items: List[Dict[str, Any]]) -> None:
            """Populate shortcut assignments from items and submenus."""
            for item in items:
                if item.get("type") == "action":
                    shortcut_num = item.get("shortcut", 0)
                    if 1 <= shortcut_num <= 9:
                        shortcuts[shortcut_num - 1]["item"] = item
                elif item.get("type") == "submenu" and "items" in item:
                    _scan_items(item["items"])

        for section in self._sections:
            _scan_items(section.get("items", []))

        return shortcuts

    def _find_command_section(self, command: str) -> str:
        """Recursively search menu sections to find section ownership."""

        def _search_items(
            items: List[Dict[str, Any]], section_title: str
        ) -> bool:
            """Find a command in the supplied items and nested submenus."""
            for item in items:
                if (
                    item.get("type") == "action"
                    and item.get("command") == command
                ):
                    return True
                if item.get("type") == "submenu" and "items" in item:
                    if _search_items(item["items"], section_title):
                        return True
            return False

        for section in self._sections:
            title = section.get("title", "General")
            if _search_items(section.get("items", []), title):
                return title
        return "Other / Unknown"

    @Slot(result="QStringList")
    def get_available_sections(self) -> List[str]:
        """Return all section titles plus 'All'."""
        sections_list = ["All"]
        for section in self._sections:
            title = section.get("title")
            if title and title not in sections_list:
                sections_list.append(title)
        return sections_list

    @Slot(str, result="QVariantList")
    def get_execution_stats(
        self, section_filter: str = "All"
    ) -> List[Dict[str, Any]]:
        """Return execution statistics filtered by section and sorted."""
        stats_list = []
        for cmd, data in self._stats.items():
            assigned_section = self._find_command_section(cmd)
            item_copy = data.copy()
            item_copy["section"] = assigned_section

            if section_filter == "All" or assigned_section == section_filter:
                stats_list.append(item_copy)

        stats_list.sort(key=lambda x: x.get("count", 0), reverse=True)

        max_count = stats_list[0].get("count", 1) if stats_list else 1
        for item in stats_list:
            count = item.get("count", 0)
            item["ratio"] = count / max_count if max_count > 0 else 0.0

        return stats_list

    @Slot()
    def reset_execution_stats(self) -> None:
        """Reset all execution statistics counters."""
        self._stats = {}
        if self._stats_file.exists():
            try:
                self._stats_file.unlink()
            except OSError:
                pass
        self.statsChanged.emit()
        self.statusNotification.emit(
            "Execution statistics successfully reset.", True
        )

    @Slot(str, result="QStringList")
    def get_arguments_history(self, command: str) -> List[str]:
        """Return unique historical arguments used for a specific command."""
        args_list = []
        for fav in self._favorites:
            if fav.get("command") == command:
                arg = fav.get("arguments", "")
                if arg and arg not in args_list:
                    args_list.append(arg)
        return args_list

    @Slot(str, result=bool)
    def export_configuration(self, file_url: str) -> bool:
        """Export configuration to a local path or file URL.

        Return whether the export succeeded and report its result to QML.
        """
        try:
            local_path = QUrl(file_url).toLocalFile() or file_url
            target_path = Path(local_path)
            if target_path.suffix.lower() != ".json":
                target_path = target_path.with_suffix(".json")
            payload = {
                "shortcut_modifier": self._shortcut_modifier,
                "show_command": self._show_command,
                "prompt_arguments": self._prompt_arguments,
                "show_output_window": self._show_output_window,
                "sections": self._sections,
            }
            with target_path.open("w", encoding="utf-8") as file:
                json.dump(payload, file, indent=4, ensure_ascii=False)
            self.statusNotification.emit(
                f"Backup exported to: {target_path.name}", True
            )
            return True
        except (OSError, ValueError) as exc:
            self.statusNotification.emit(f"Export error: {exc}", False)
            return False

    @Slot(str, result=bool)
    def import_configuration(self, file_url: str) -> bool:
        """Import a JSON backup from a local path or file URL.

        Return whether the import succeeded and report its result to QML.
        """
        try:
            local_path = QUrl(file_url).toLocalFile() or file_url
            source_path = Path(local_path)
            with source_path.open("r", encoding="utf-8") as file:
                parsed_data = json.load(file)
            if (
                not isinstance(parsed_data, dict)
                or "sections" not in parsed_data
            ):
                self.statusNotification.emit("Invalid file structure.", False)
                return False
            self._sections = parsed_data["sections"]
            self._shortcut_modifier = parsed_data.get(
                "shortcut_modifier", "Ctrl+Shift"
            )
            self._show_command = bool(parsed_data.get("show_command", False))
            self._prompt_arguments = bool(
                parsed_data.get("prompt_arguments", False)
            )
            self._show_output_window = bool(
                parsed_data.get("show_output_window", True)
            )
            self._save_config_file()
            self.sectionsChanged.emit()
            self.modifierChanged.emit()
            self.showCommandChanged.emit()
            self.promptArgumentsChanged.emit()
            self.showOutputWindowChanged.emit()
            self.statusNotification.emit(
                f"Backup imported: {source_path.name}", True
            )
            return True
        except (json.JSONDecodeError, OSError, ValueError) as exc:
            self.statusNotification.emit(f"Import error: {exc}", False)
            return False

    @Slot(str, result="QStringList")
    def get_system_icons(self, query: str) -> List[str]:
        """Return standard system icon names matching the search query."""
        common_icons = [
            "folder",
            "folder-open",
            "utilities-terminal",
            "utilities-system-monitor",
            "system-software-update",
            "applications-development",
            "applications-other",
            "code-context",
            "folder-sync",
            "network-workgroup",
            "network-wired",
            "network-connect",
            "document-save",
            "edit-delete",
            "configure",
            "dialog-ok",
            "dialog-error",
            "dialog-warning",
            "system-run",
        ]
        return [
            i for i in common_icons if not query.strip() or query.lower() in i
        ]

    @Slot(str, result=bool)
    def save_configuration_json(self, json_string: str) -> bool:
        """Save a JSON configuration containing a ``sections`` field."""
        try:
            parsed_data = json.loads(json_string)
            if "sections" not in parsed_data:
                return False
            self._sections = parsed_data.get("sections", [])
            self._save_config_file()
            self.sectionsChanged.emit()
            return True
        except (json.JSONDecodeError, OSError):
            return False

    @Slot(str, str, str)
    def remove_recent(self, name: str, command: str, arguments: str) -> None:
        """Remove a recent item without changing the menu or statistics.

        Match by name, command and arguments, and restore the in-memory
        history if the updated history cannot be saved.
        """
        previous = self._favorites
        self._favorites = [
            item
            for item in previous
            if not (
                item.get("name", "") == name
                and item.get("command", "") == command
                and item.get("arguments", "") == arguments
            )
        ]
        if len(self._favorites) == len(previous):
            self.statusNotification.emit("Recent item not found.", False)
        elif self._save_history():
            self.favoritesChanged.emit()
        else:
            self._favorites = previous

    @Slot(dict, str)
    def record_history(self, item: Dict[str, Any], arguments: str) -> None:
        """Record an execution in recent history and update statistics.

        The history keeps at most ten entries and deduplicates by command and
        arguments. Statistics are accumulated per command.
        """
        command = item.get("command", "")
        name = item.get("name", "Unknown")
        icon = item.get("icon", "application-x-executable")
        if not command.strip():
            return

        self._favorites = [
            fav
            for fav in self._favorites
            if not (
                fav.get("command") == command
                and fav.get("arguments", "") == arguments
            )
        ]
        history_entry = {
            "name": name,
            "description": item.get("description", command),
            "icon": icon,
            "command": command,
            "arguments": arguments,
            "type": "action",
            "prompt_arguments": bool(item.get("prompt_arguments", False)),
            "detached": bool(item.get("detached", False)),
            "notify": bool(item.get("notify", True)),
            "show_output": bool(item.get("show_output", False)),
        }
        self._favorites.insert(0, history_entry)
        if len(self._favorites) > 10:
            self._favorites = self._favorites[:10]
        self._save_history()
        self.favoritesChanged.emit()

        if command not in self._stats:
            self._stats[command] = {
                "name": name,
                "command": command,
                "icon": icon,
                "count": 0,
                "last_executed": "",
            }
        self._stats[command]["count"] += 1
        self._stats[command]["last_executed"] = datetime.now().strftime(
            "%Y-%m-%d %H:%M:%S"
        )
        self._save_stats()
        self.statsChanged.emit()

    @Slot(str, result="QVariantList")
    def search_items(self, query: str) -> List[Dict[str, Any]]:
        """Return actions whose names or descriptions match the query."""
        results: List[Dict[str, Any]] = []
        if not query.strip():
            return results
        search_query = query.lower()

        def _recurse(items: List[Dict[str, Any]], path: str) -> None:
            """Collect matches and their paths from nested menu items."""
            for item in items:
                name = item.get("name", "")
                description = item.get("description", "")
                current_path = f"{path} > {name}" if path else name
                if (
                    search_query in name.lower()
                    or search_query in description.lower()
                ):
                    if item.get("type") == "action":
                        match_item = item.copy()
                        match_item["breadcrumb"] = current_path
                        results.append(match_item)
                if item.get("type") == "submenu" and "items" in item:
                    _recurse(item["items"], current_path)

        for section in self._sections:
            _recurse(section.get("items", []), section.get("title", ""))
        return results


def _config_dir() -> Path:
    """Return and create Kumi's XDG configuration directory."""
    xdg_config_home = os.environ.get("XDG_CONFIG_HOME")
    config_home = (
        Path(xdg_config_home) if xdg_config_home else Path.home() / ".config"
    )
    if not config_home.is_absolute():
        config_home = Path.home() / ".config"
    config_dir = config_home / "kumi"
    config_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    return config_dir


def main() -> int:
    """Initialize and execute the Kirigami application launcher."""
    _clean_old_temp_logs()
    os.environ["QT_QUICK_CONTROLS_STYLE"] = "org.kde.desktop"
    app = QGuiApplication(sys.argv)
    app.setApplicationName("Kumi")
    app.setApplicationVersion(__version__)
    app.setOrganizationName("CustomTools")
    app.setDesktopFileName("kumi")

    base_dir = Path(__file__).resolve().parent
    app.setWindowIcon(QIcon(str(base_dir / "icons" / "kumi.svg")))
    config_file = _config_dir() / "kumi_config.json"
    qml_file = base_dir / "main.qml"

    backend = LauncherBackend(config_file)
    process_runner = ProcessRunner()

    engine = QQmlApplicationEngine()
    engine.rootContext().setContextProperty("backend", backend)
    engine.rootContext().setContextProperty("processRunner", process_runner)
    engine.load(str(qml_file))

    if not engine.rootObjects():
        return -1
    return app.exec()


if __name__ == "__main__":
    sys.exit(main())
